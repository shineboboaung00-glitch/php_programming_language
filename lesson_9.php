<?php  // lesson_9 (looping) — Loops (ထပ်ခါထပ်ခါ အလုပ်လုပ်ခြင်း)

// PHP မှာ Looping (ကွင်းဆက်) ဆိုတာ သတ်မှတ်ထားတဲ့ စည်းကမ်းချက် 
// (Condition) တစ်ခု မှန်ကန်နေသမျှ ကာလပတ်လုံး Code တွေကို ထပ်ခါထပ်ခါ 
// လုပ်ဆောင်ပေးတဲ့ နည်းလမ်းဖြစ်ပါတယ်။ Data တွေကို တကြောင်းချင်းစီ ထုတ်ပြချင်တဲ့အခါ 
// ဒါမှမဟုတ် ထပ်ခါထပ်ခါ လုပ်ရမယ့် အလုပ်တွေကို ရေးသားတဲ့အခါ Loop တွေကို အသုံးပြုပါတယ်။

// PHP Loop (၄) မျိုး

// for loop: ထပ်ခါထပ်ခါ လုပ်ဆောင်ရမယ့် အကြိမ်ရေ အတိအကျ ကို သိရှိတဲ့အခါ သုံးပါတယ်။

// Syntax:

// for (စတင်မယ့်တန်ဖိုး; စည်းကမ်းချက်; တိုးမြှင့်/လျော့ချခြင်း) {
//      လုပ်ဆောင်ရမယ့် code များ
// }

// ၁ ကနေ ၅ အထိ ပရင့်ထုတ်မည်

for ($i = 1; $i <= 5; $i++) {
    echo "Count: $i <br>";
}

// ================================================================================================================================

// while loop: ပေးထားတဲ့ စည်းကမ်းချက် (Condition) 
// မှန်နေသမျှ စာကြောင်းများကို ထပ်ခါထပ်ခါ လုပ်ဆောင်ပေးပါတယ်။ 
// ပထမဆုံး စည်းကမ်းချက်ကို စစ်ဆေးပြီးမှ Code ကို လုပ်ဆောင်တာဖြစ်ပါတယ်။

// Syntax:

// while (စည်းကမ်းချက်) {
//      လုပ်ဆောင်ရမယ့် code များ
// }


$x = 1;

while($x <= 3) {
    echo "Count is: $x <br>";
    $x++;
}


// while loop: အခြေအနေ မှန်နေသမျှ ပတ်မည်။

// while loop: စစ်တယ် -> မှန်မှ အလုပ်လုပ်တယ်။

// ================================================================================================================================

// do...while loop: while loop နဲ့ ဆင်တူသော်လည်း ကွဲပြားချက်မှာ Condition ကို မစစ်မီ Code ကို 
// အနည်းဆုံး (၁) ကြိမ် အရင်လုပ်ဆောင်ခြင်း ဖြစ်ပါတယ်။ Condition မှားနေရင်တောင် ပထမတစ်ကြိမ် အလုပ်လုပ်မှာ ဖြစ်ပါတယ်။


// Syntax:

// do {
//      လုပ်ဆောင်ရမယ့် code များ
// } while (စည်းကမ်းချက်);


$x = 6;

do {
    echo "Number: $x <br>"; // Condition မှားနေပေမယ့် ၁ ကြိမ် အလုပ်လုပ်ပါမည်
    $x++;
} while ($x <= 5);


// do...while loop: အလုပ်လုပ်တယ် -> ပြီးမှ စစ်တယ် (အနည်းဆုံး ၁ ကြိမ် အမြဲ အလုပ်လုပ်သည်)။

// ================================================================================================================================

// foreach loop: foreach loop ကို Array တွေထဲမှာရှိတဲ့ Data တွေကို တစ်ခုချင်းစီ 
// ထုတ်ယူကြည့်ရှုချင်တဲ့အခါမှာ သီးသန့် အသုံးပြုပါတယ်။

// Syntax:

// foreach ($array as $value) {
//      လုပ်ဆောင်ရမယ့် code များ
// }

$colors = array("Red", "Green", "Blue");

foreach ($colors as $value) {
    echo "$value <br>";
}

// ================================================================================================================================

// Control Statements (Loop ကို ထိန်းချုပ်ခြင်း)

// Loop ပတ်နေစဉ်မှာ အခြေအနေပေါ်မူတည်ပြီး လမ်းကြောင်းပြောင်းချင်ရင် အောက်ပါ Statement တွေကို သုံးနိုင်ပါတယ် -

// break: Loop ပတ်နေတာကို ချက်ချင်း ရပ်တန့်ပြီး ထွက်လိုက်တာပါ။

// continue: လက်ရှိ ရောက်နေတဲ့ အကြိမ်ကို ကျော်လွန် (Skip လုပ်) ပြီး နောက်တစ်ကြိမ် Loop သို့ ဆက်သွားတာပါ။

// အနှစ်ချုပ်:

// အကြိမ်ရေ အတိအကျ သိရင် for ကို သုံးပါ။

// အခြေအနေ Condition အပေါ် မူတည်ရင် while ကို သုံးပါ။

// အနည်းဆုံး တစ်ကြိမ် အလုပ်လုပ်စေချင်ရင် do...while ကို သုံးပါ။

// Array ထဲက Data တွေကို ပတ်ထုတ်ချင်ရင် foreach ကို သုံးပါ။

?>